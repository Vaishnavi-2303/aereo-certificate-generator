from pathlib import Path
from reportlab.lib.pagesizes import A4, landscape
from reportlab.pdfgen import canvas
from reportlab.lib import colors

OUTPUT_DIR = Path("data/certificates")
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


def generate_certificate(recipient, output_path: Path) -> None:
    """Render one certificate using the application's single predefined template."""
    page_width, page_height = landscape(A4)
    c = canvas.Canvas(str(output_path), pagesize=(page_width, page_height))

    c.setStrokeColor(colors.HexColor("#1f3a5f"))
    c.setLineWidth(3)
    c.rect(30, 30, page_width - 60, page_height - 60)
    c.setLineWidth(1)
    c.rect(42, 42, page_width - 84, page_height - 84)

    c.setFillColor(colors.HexColor("#1f3a5f"))
    c.setFont("Helvetica-Bold", 30)
    c.drawCentredString(page_width / 2, page_height - 115, "CERTIFICATE OF COMPLETION")

    c.setFillColor(colors.black)
    c.setFont("Helvetica", 15)
    c.drawCentredString(page_width / 2, page_height - 160, "This certificate is proudly presented to")

    c.setFillColor(colors.HexColor("#1f3a5f"))
    c.setFont("Helvetica-Bold", 28)
    c.drawCentredString(page_width / 2, page_height - 215, recipient.name)

    c.setFillColor(colors.black)
    c.setFont("Helvetica", 15)
    c.drawCentredString(page_width / 2, page_height - 255, "for successfully completing")

    c.setFillColor(colors.HexColor("#333333"))
    c.setFont("Helvetica-Bold", 20)
    c.drawCentredString(page_width / 2, page_height - 295, recipient.course)

    c.setFont("Helvetica", 12)
    c.drawCentredString(page_width / 2, 95, f"Completion date: {recipient.completion_date}")
    c.setFont("Helvetica-Oblique", 10)
    c.drawCentredString(page_width / 2, 70, "Generated by Aereo Certificate Generator")
    c.save()
